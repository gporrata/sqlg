function theme(spec: Spec): AppTheme {
  const darkTip = {
    tip: "#2a2a2e",
    tipFg: "#f5f5f7",
    tipBd: "#52525a",
    tipErr: "#3d1c1a",
    tipErrFg: "#ffd4ce",
    tipErrBd: "#ff6b61",
    tipWarn: "#3a3014",
    tipWarnFg: "#ffe6ad",
    tipWarnBd: "#e2b15a",
    err: "#ffb1a8",
    errBg: "#3d1c1a",
    ok: "#7ddea0",
    banner: "#3a3014",
    bannerFg: "#ffe6ad",
  };
  const lightTip = {
    tip: "#ffffff",
    tipFg: "#1d1d1f",
    tipBd: "#c5c5ca",
    tipErr: "#fff1f0",
    tipErrFg: "#8d1d18",
    tipErrBd: "#d70015",
    tipWarn: "#fff8e6",
    tipWarnFg: "#6a4c00",
    tipWarnBd: "#c48a00",
    err: "#b42318",
    errBg: "#fff1f0",
    ok: "#187a32",
    banner: "#fff6d8",
    bannerFg: "#6a4c00",
  };
  const tone = spec.dark ? darkTip : lightTip;
  return {
    id: spec.id,
    name: spec.name,
    dark: spec.dark,
    vars: {
      "--win": spec.win,
      "--side": spec.side,
      "--bar": spec.bar,
      "--tool": spec.tool,
      "--bd": spec.bd,
      "--fg": spec.fg,
      "--mut": spec.mut,
      "--accent": spec.accent,
      "--accent-fg": spec.accentFg,
      "--line": spec.line,
      "--sel": spec.sel,
      "--sel-fg": spec.selFg,
      "--ed-bg": spec.edBg,
      "--ed-fg": spec.edFg,
      "--ed-caret": spec.caret,
      "--ed-line": spec.lineHl,
      "--ed-ran": "color-mix(in srgb, var(--accent) 24%, transparent)",
      "--ed-mark": "color-mix(in srgb, var(--sel) 32%, transparent)",
      "--syn-keyword": spec.keyword,
      "--syn-operator": spec.operator,
      "--syn-string": spec.string,
      "--syn-number": spec.number,
      "--syn-type": spec.type,
      "--syn-comment": spec.comment,
      "--tip": spec.tip ?? tone.tip,
      "--tip-fg": spec.tipFg ?? tone.tipFg,
      "--tip-bd": spec.tipBd ?? tone.tipBd,
      "--tip-err": spec.tipErr ?? tone.tipErr,
      "--tip-err-fg": spec.tipErrFg ?? tone.tipErrFg,
      "--tip-err-bd": spec.tipErrBd ?? tone.tipErrBd,
      "--tip-warn": spec.tipWarn ?? tone.tipWarn,
      "--tip-warn-fg": spec.tipWarnFg ?? tone.tipWarnFg,
      "--tip-warn-bd": spec.tipWarnBd ?? tone.tipWarnBd,
      "--err": tone.err,
      "--err-bg": tone.errBg,
      "--ok": tone.ok,
      "--banner": tone.banner,
      "--banner-fg": tone.bannerFg,
      ...(spec.dark ? darkPills : lightPills),
      ...(spec.dark ? darkTones : lightTones),
    },
  };
}

