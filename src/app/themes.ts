const byId = new Map(THEMES.map((item) => [item.id, item]));

export function themeById(id: string | null | undefined): AppTheme {
  if (!id) return byId.get("light") as AppTheme;
  return byId.get(id) ?? (byId.get("light") as AppTheme);
}

export function applyTheme(id: string | null | undefined): AppTheme {
  const theme = themeById(id);
  const root = document.documentElement;
  root.dataset.theme = theme.id;
  root.dataset.tone = theme.dark ? "dark" : "light";
  root.style.colorScheme = theme.dark ? "dark" : "light";
  for (const [key, value] of Object.entries(theme.vars)) {
    root.style.setProperty(key, value);
  }
  return theme;
}
